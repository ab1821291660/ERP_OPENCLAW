"""Stage 17 — Sitecustomize Injection.

For child processes that aren't running under pytest, install patching
at Python startup using the ``site`` machinery: write a
``sitecustomize.py`` into a runtime directory and prepend that directory
to ``PYTHONPATH``.  Python imports it before any user code runs.

Run::

    uv run python stages_c/stage_17_sitecustomize_injection.py
"""

from __future__ import annotations

import importlib
import json
import os
import subprocess
import sys
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path

VARIANT_ENV = "BETTER_HARNESS_VARIANT_FILE"

# A live module-level value the child will read.
BASE_PROMPT = "You are a helpful assistant."


@dataclass(frozen=True)
class Variant:
    label: str
    overrides: dict[str, str]

    def save(self, path: Path) -> None:
        path.write_text(json.dumps(asdict(self), indent=2, sort_keys=True))

    @classmethod
    def load(cls, path: Path) -> Variant:
        payload = json.loads(path.read_text())
        return cls(label=payload["label"], overrides=payload["overrides"])


def patch_module_attrs(overrides: dict[str, str]) -> None:
    for target, value in overrides.items():
        module_name, separator, attribute = target.partition(":")
        if not separator:
            msg = f"invalid module_attr target {target!r}; expected module:attribute"
            raise ValueError(msg)
        module = importlib.import_module(module_name)
        setattr(module, attribute, value)


def patch_from_env() -> None:
    """Read the env-pinned variant file (if any) and apply it."""
    raw_path = os.environ.get(VARIANT_ENV)
    if not raw_path:
        return
    variant = Variant.load(Path(raw_path))
    patch_module_attrs(variant.overrides)


# ── The new piece ─────────────────────────────────────────────────────────


SITECUSTOMIZE_SOURCE = """\
# Auto-generated by stage_17_sitecustomize_injection.py.
# Python's site machinery imports this at interpreter startup, so the
# variant patch is applied before any user code runs.
from stages_c.stage_17_sitecustomize_injection import patch_from_env

patch_from_env()
"""


def ensure_sitecustomize(runtime_dir: Path) -> Path:
    """Write a ``sitecustomize.py`` that calls ``patch_from_env``.

    Args:
        runtime_dir: Directory the file is written into; created if absent.

    Returns:
        The directory it was written into (so the caller can put it on
        ``PYTHONPATH``).
    """
    runtime_dir.mkdir(parents=True, exist_ok=True)
    (runtime_dir / "sitecustomize.py").write_text(SITECUSTOMIZE_SOURCE)
    return runtime_dir


def prepend_pythonpath(paths: list[Path], existing: str | None) -> str:
    """Put ``paths`` first in a ``PYTHONPATH`` string."""
    parts = [str(path) for path in paths]
    if existing:
        parts.append(existing)
    return os.pathsep.join(parts)


# ── Demo ──────────────────────────────────────────────────────────────────
#
# A *non-pytest* child entrypoint.  Notice it never calls patch_from_env()
# itself — that's the whole point: sitecustomize.py runs before this
# script's first line.

CHILD_SCRIPT = """\
from stages_c.stage_17_sitecustomize_injection import BASE_PROMPT
print(BASE_PROMPT)
"""


def main() -> None:
    print("Stage 17 — Sitecustomize Injection\n")

    walkthrough_root = Path(__file__).resolve().parents[1]

    with tempfile.TemporaryDirectory(prefix="bh_stage17_") as tmpdir:
        tmp = Path(tmpdir)

        runtime_dir = ensure_sitecustomize(tmp / "runtime")
        sitecustomize_path = runtime_dir / "sitecustomize.py"
        print(f"sitecustomize → {sitecustomize_path}")
        print(f"contents:\n{sitecustomize_path.read_text().rstrip()}\n")

        variant = Variant(
            label="iter-001",
            overrides={
                "stages_c.stage_17_sitecustomize_injection:BASE_PROMPT": (
                    "You are a careful math assistant. "
                    "Always use the calculator tool for arithmetic."
                ),
            },
        )
        variant_path = tmp / "variant.json"
        variant.save(variant_path)

        env = os.environ.copy()
        env["PYTHONPATH"] = prepend_pythonpath(
            [runtime_dir, walkthrough_root],
            env.get("PYTHONPATH"),
        )
        # env["PYTHONPATH"] = env.get("PYTHONPATH") or ""
        env[VARIANT_ENV] = str(variant_path)

        print(f"PYTHONPATH = {env['PYTHONPATH']}")
        print(f"{VARIANT_ENV} = {env[VARIANT_ENV]}\n")

        completed = subprocess.run(
            [sys.executable, "-c", CHILD_SCRIPT],
            env=env,
            capture_output=True,
            text=True,
            check=True,
        )
        out = completed.stdout.strip()
        print(f"child output: {out!r}")

        assert out.startswith("You are a careful math assistant"), out

    print("\n" + "=" * 60)
    print("sitecustomize.py ran before the child's first line of code —")
    print("no explicit patch_from_env() call required in the entrypoint.")


if __name__ == "__main__":
    main()
