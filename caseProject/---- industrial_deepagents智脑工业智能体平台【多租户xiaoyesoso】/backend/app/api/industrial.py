router = APIRouter(prefix="/industrial", tags=["industrial"])

ALLOWED_FILES = {
    ".txt": {"text/plain"}, ".md": {"text/markdown", "text/plain"},
    ".pdf": {"application/pdf"}, ".docx": {"application/vnd.openxmlformats-officedocument.wordprocessingml.document"},
    ".xlsx": {"application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"},
    ".csv": {"text/csv", "application/csv", "text/plain", "application/vnd.ms-excel"},
    ".png": {"image/png"}, ".jpg": {"image/jpeg"}, ".jpeg": {"image/jpeg"},
    ".dwg": {"application/acad", "application/octet-stream"}, ".dxf": {"application/dxf", "application/octet-stream"},
}


def _safe_filename(filename: str) -> str:
    name = unicodedata.normalize("NFKC", Path(filename or "unnamed").name)
    return re.sub(r"[^\w.()\- ]", "_", name, flags=re.UNICODE)[:180] or "unnamed"


def _project(db, tenant_id: str, project_id: str):
    return db.execute("SELECT id FROM projects WHERE id=? AND tenant_id=?", (project_id, tenant_id)).fetchone()

# Platform skills library: deepagents skills (see SkillsMiddleware) rooted at
# backend/skills/<skill-name>/SKILL.md. The catalog below is generated by
# scanning that directory so frontmatter stays the single source of truth.
SKILLS_DIR = Path(__file__).resolve().parents[2] / "skills"

# Data-source wiring status per skill (deployment fact, not frontmatter):
# knowledge-search answers from the live industrial knowledge base; web-search
# runs on the live DuckDuckGo backend; the rest run on bundled demo data or
# are not wired to a live system yet.
DATA_LIVE_SKILLS = {"knowledge-search", "web-search"}
PARSER_SKILLS = {
    ".txt": "text-file-parser",
    ".md": "text-file-parser",
    ".pdf": "pdf-parser",
    ".docx": "office-parser",
    ".xlsx": "spreadsheet-parser",
    ".csv": "spreadsheet-parser",
    ".png": "image-drawing-parser",
    ".jpg": "image-drawing-parser",
    ".jpeg": "image-drawing-parser",
    ".dwg": "image-drawing-parser",
    ".dxf": "image-drawing-parser",
}
def _parser(filename: str, content_type: str) -> str:
    suffix = Path(filename or "").suffix.lower()
    skill = PARSER_SKILLS.get(suffix, "")
    if skill and content_type:
        allowed_types = ALLOWED_FILES[suffix] | {"application/octet-stream"}
        if content_type not in allowed_types:
            raise HTTPException(415, "文件类型与扩展名不匹配")
    return skill


def _parse_frontmatter(content: str) -> dict:
    """Extract YAML frontmatter from SKILL.md content; empty dict on failure."""
    match = re.match(r"^---\s*\n(.*?)\n---\s*\n", content, re.DOTALL)
    if not match:
        return {}
    try:
        data = yaml.safe_load(match.group(1))
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}


def _skill_catalog() -> list[dict]:
    """Scan the platform skills library into the API catalog shape."""
    items: list[dict] = []
    if not SKILLS_DIR.is_dir():
        return items
    for skill_md in sorted(SKILLS_DIR.glob("*/SKILL.md")):
        meta = _parse_frontmatter(skill_md.read_text(encoding="utf-8"))
        name = str(meta.get("name", "")).strip()
        description = str(meta.get("description", "")).strip()
        if not name or not description:
            continue  # skip malformed skills (mirrors SkillsMiddleware behavior)
        extra = meta.get("metadata") if isinstance(meta.get("metadata"), dict) else {}
        items.append({
            "name": name,
            "label": str(extra.get("label", "") or name),
            "description": description,
            "icon": str(extra.get("icon", "") or "brain"),
            "category": str(extra.get("category", "") or "通用"),
            "connected": True,  # packaged as a callable deepagents skill
            "data_live": name in DATA_LIVE_SKILLS,
        })
    return items


@router.get("/knowledge")
def search_knowledge(
    q: str = Query(default="", max_length=200),
    family: str = Query(default="", max_length=40),
    category: str = Query(default="", max_length=40),
    limit: int = Query(default=50, ge=1, le=200),
    ctx: Context = Depends(require_login), db=Depends(get_db),
):
    items = knowledge_repo.list_knowledge(db, q=q, family=family, category=category, limit=limit)
    return {"items": items}


@router.get("/skills")
def list_skills(ctx: Context = Depends(require_login)):
    return {"items": _skill_catalog()}

def _require_project(db, ctx: Context, project_id: str):
    project = _project(db, ctx.tenant_id, project_id)
    if not project:
        raise HTTPException(404, "项目不存在")
    return project


def _get_file(db, ctx: Context, file_id: str, project_id: str):
    _require_project(db, ctx, project_id)
    row = db.execute(
        "SELECT * FROM industrial_files WHERE id=? AND tenant_id=? AND project_id=?",
        (file_id, ctx.tenant_id, project_id),
    ).fetchone()
    if not row:
        raise HTTPException(404, "文件不存在")
    return row


@router.post("/files")
async def upload_file(
    project_id: str,
    file: UploadFile = File(...),
    ctx: Context = Depends(require_member),
    db=Depends(get_db),
):
    _require_project(db, ctx, project_id)

    raw_name = file.filename or ""
    safe_name = _safe_filename(raw_name)
    suffix = Path(safe_name).suffix.lower()
    if suffix not in ALLOWED_FILES:
        raise HTTPException(415, "不支持的文件类型")

    content_type = (file.content_type or "").split(";", 1)[0].strip().lower()
    if not content_type:
        raise HTTPException(415, "缺少文件 Content-Type")
    parser_skill = _parser(safe_name, content_type)

    settings = get_settings()
    chunks: list[bytes] = []
    size = 0
    while chunk := await file.read(1024 * 1024):
        size += len(chunk)
        if size > settings.max_upload_size:
            raise HTTPException(413, "文件超过大小限制")
        chunks.append(chunk)
    data = b"".join(chunks)

    file_id = str(uuid4())
    object_name = f"{ctx.tenant_id}/{project_id}/{file_id}/{safe_name}"
    try:
        MinioService(settings=settings).put(object_name, data, content_type)
    except HTTPException:
        raise
    except RuntimeError as exc:
        raise HTTPException(503, "文件存储服务不可用") from exc
    except Exception as exc:
        raise HTTPException(502, "文件写入对象存储失败") from exc

    db.execute(
        """
        INSERT INTO industrial_files
            (id, tenant_id, project_id, filename, object_name, content_type,
             size, parser_skill, status, created_at, uploaded_by)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'uploaded', ?, ?)
        """,
        (file_id, ctx.tenant_id, project_id, safe_name, object_name,
         content_type, size, parser_skill, utcnow(), ctx.user_id),
    )
    db.commit()
    return {
        "id": file_id,
        "project_id": project_id,
        "filename": safe_name,
        "size": size,
        "content_type": content_type,
        "parser_skill": parser_skill,
        "status": "uploaded",
    }


@router.get("/files")
def list_files(project_id: str, ctx: Context = Depends(require_login), db=Depends(get_db)):
    _require_project(db, ctx, project_id)
    rows = db.execute(
        "SELECT * FROM industrial_files WHERE tenant_id=? AND project_id=? ORDER BY created_at DESC",
        (ctx.tenant_id, project_id),
    ).fetchall()
    return {"items": [dict(row) for row in rows]}


@router.get("/files/{file_id}")
def file_detail(
    file_id: str,
    project_id: str = Query(...),
    ctx: Context = Depends(require_login),
    db=Depends(get_db),
):
    return dict(_get_file(db, ctx, file_id, project_id))


@router.post("/files/{file_id}/parse")
def parse_file(
    file_id: str,
    project_id: str = Query(...),
    ctx: Context = Depends(require_member),
    db=Depends(get_db),
):
    row = _get_file(db, ctx, file_id, project_id)
    next_status = "queued" if row["parser_skill"] else "unsupported"
    db.execute(
        "UPDATE industrial_files SET status=? WHERE id=? AND tenant_id=? AND project_id=?",
        (next_status, file_id, ctx.tenant_id, project_id),
    )
    db.commit()
    return {
        "file_id": file_id,
        "project_id": project_id,
        "parser_skill": row["parser_skill"],
        "status": next_status,
    }
